import com.example.calofit.domain.calendar.JalaliCalendarHelper
import java.util.Locale

object StringsProvider {

    fun get(key: String, isPersian: Boolean): String {
        val raw = if (isPersian) fa[key] ?: en[key] ?: key else en[key] ?: key
        return if (isPersian) JalaliCalendarHelper.toPersianDigits(raw) else raw
    }

    fun formatNumber(number: Number, isPersian: Boolean): String {
        val raw = number.toString()
        return if (isPersian) JalaliCalendarHelper.toPersianDigits(raw) else raw
    }

    fun formatDecimal(value: Double, isPersian: Boolean, decimals: Int = 1): String {
        val raw = String.format(Locale.US, "%.${decimals}f", value)
        return if (isPersian) JalaliCalendarHelper.toPersianDigits(raw) else raw
    }

    fun localizeDigits(text: String, isPersian: Boolean): String {
        return JalaliCalendarHelper.formatDigitsForLanguage(text, isPersian)
    }

